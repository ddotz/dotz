test("an English conventional prefix is refused, except 내부 정리: and release:", () => {
	for (const subject of ["omp: coding lane이 done gate를 싣는다", "guard: 하네스 경계를 막습니다", "feat(hub): 새 카드를 보여요", "fix: 답이 사라지지 않아요", "Fix/web: 창이 떠요", "docs: 설명을 고쳐요"]) {
		expect(subjectRules(subject, BODY), subject).toContain("prefix");
	}
	expect(subjectRules("내부 정리: 화면 목록을 한 표로 모아요", BODY)).toEqual([]);
	expect(subjectRules("release: v261118.2", "")).toEqual([]);
	expect(subjectRules("omp lane을 나눠 done gate를 싣습니다", BODY)).toEqual([]);
	expect(subjectRules("widgets: false는 omp 설정이에요", BODY)).toContain("prefix");
	expect(subjectRules("omp에서 widgets: false를 넣습니다", BODY)).toEqual([]);
});

test("a plain declarative ending is refused, the polite endings are not", () => {
	for (const subject of ["omp 작업자도 done gate를 싣는다", "메일 답장을 남기지 않는다.", "화면이 바뀐다", "이 변경은 정답이 아니다", "오래된 파일을 지니다"]) {
		expect(subjectRules(subject, BODY), subject).toEqual(["ending"]);
	}
	for (const subject of ["답이 사라지지 않습니다", "이 변경은 정답이 아닙니다", "답이 사라지지 않아요", "창이 열려요", "목록이 보내져요", "알림이 나와요.", "문서로 옮김", "이름을 바로잡음"]) {
		expect(subjectRules(subject, BODY), subject).toEqual([]);
	}
});

test("a body needs a line that starts with 왜: or 어떻게:, a label inside a sentence or after a bullet does not count, a release commit is exempt", () => {
	expect(subjectRules("답이 사라지지 않아요", "")).toEqual(["body"]);
	expect(subjectRules("답이 사라지지 않아요", "이유를 적었어요. 왜: 이 줄은 문장 안이에요")).toEqual(["body"]);
	expect(subjectRules("답이 사라지지 않아요", "- 왜: 목록 앞에 붙였어요")).toEqual(["body"]);
	expect(subjectRules("답이 사라지지 않아요", "첫 줄\n어떻게: 디스크에 남겨요")).toEqual([]);
	expect(subjectRules("답이 사라지지 않아요", "  왜: 들여써도 줄 처음이에요")).toEqual([]);
	expect(subjectRules("release: v261118.3", "")).toEqual([]);
	expect(subjectRules("omp: 두 가지를 어긴다", "")).toEqual(["prefix", "ending", "body"]);
});

test("the refusal names each commit by short sha, subject and one rule sentence, and hides a subject that holds an install value", () => {
	const found = [{ sha: "abc1234", subject: "guard: 하네스를 막는다", rules: subjectRules("guard: 하네스를 막는다", "") }];
	const text = subjectRefusal(found, []);
	expect(text).toContain('abc1234 "guard: 하네스를 막는다": 제목은 `omp:`나 `feat(x):`');
	expect(text).toContain("제목은 `~합니다`나 `~해요`");
	expect(text).toContain("본문에는 `왜:`나 `어떻게:`");
	expect(text.split("abc1234").length).toBe(2);
	expect(text).toContain("CONTRIBUTING.md");
	const hidden = subjectRefusal([{ sha: "def5678", subject: "zebrafish-private-term을 지운다", rules: ["ending"] }], [{ value: "zebrafish-private-term", label: "private term" }]);
	expect(hidden).not.toContain("zebrafish");
	expect(hidden).toContain("def5678");
});
