import { afterAll, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { extensionFeatures } from "./features.ts";

const root = mkdtempSync(join(tmpdir(), "dotz-ext-"));
const saved = { omo: process.env.OMO_CODING_AGENT_DIR, omp: process.env.PI_CODING_AGENT_DIR };
afterAll(() => {
	for (const [k, v] of [["OMO_CODING_AGENT_DIR", saved.omo], ["PI_CODING_AGENT_DIR", saved.omp]] as const) if (v === undefined) delete process.env[k]; else process.env[k] = v;
	rmSync(root, { recursive: true, force: true });
});

test("구성 lists only what the running harness loads as live; another harness's extensions are inactive", () => {
	const omo = join(root, "omo"), omp = join(root, "omp");
	mkdirSync(join(omo, "extensions"), { recursive: true });
	mkdirSync(join(omp, "extensions"), { recursive: true });
	writeFileSync(join(omo, "extensions", "tps.js"), '// Generated by omo. Delete this file to stop loading the default global extension.\nexport { default } from "file:///x/builtin/tps.js";\n');
	writeFileSync(join(omp, "extensions", "orchestrator-guard.ts"), "// orchestrator-guard: blocks risky worker calls.\n");
	process.env.OMO_CODING_AGENT_DIR = omo;
	process.env.PI_CODING_AGENT_DIR = omp;
	const on = Object.fromEntries(extensionFeatures(["omo"]).map(f => [f.id, f]));
	expect(on["ext-dotz"]).toMatchObject({ form: "확장", enabled: true });
	expect(on["ext-tps"]).toMatchObject({ enabled: true });
	expect(on["ext-tps"].inactive).toBeUndefined();
	expect(on["ext-orchestrator-guard"]).toMatchObject({ enabled: false, inactive: true });
	const onOmp = Object.fromEntries(extensionFeatures(["omp"]).map(f => [f.id, f]));
	expect(onOmp["ext-orchestrator-guard"]).toMatchObject({ enabled: true });
	expect(onOmp["ext-tps"]).toMatchObject({ enabled: false, inactive: true });
});
