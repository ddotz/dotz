import { readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { extractOpenSitesFromText } from "./ui-surfaces";

// The screen map in docs/ui-screens.md, drawn from the code: one Mermaid subgraph per web area (hub/web-areas.json), holding the screens
// whose view is declared there and the overlay kinds its code opens; one arrow per (area, go, screen) with the number of go() calls.
// No line numbers and no function names, so moving code without changing what opens what leaves the file as it is.
// `bun hub/screen-map.ts` writes it; `bun hub/screen-map.ts --check` exits 1 and prints the differing lines when it is stale.
const ROOT = join(import.meta.dir, "..");
export const MAP_FILE = "docs/ui-screens.md";
// web/custom.js is the owner's own card code, not a web/js file, so it has no row in hub/web-areas.json.
const CUSTOM_AREA = "custom";
// Kinds that declare a screen or a markup element rather than open something.
const DECLARED = new Set(["view", "html"]);

type Surface = { id: string; name: string; sites: string[] };
export type MapInput = { files: Record<string, string>; surfaces: Surface[]; areas: Record<string, string | string[]> };

export function readInput(root = ROOT): MapInput {
	const web = join(root, "web"), files: Record<string, string> = {};
	for (const f of readdirSync(join(web, "js")).filter(f => f.endsWith(".js"))) files[`js/${f}`] = readFileSync(join(web, "js", f), "utf8");
	files["custom.js"] = readFileSync(join(web, "custom.js"), "utf8");
	files["index.html"] = readFileSync(join(web, "index.html"), "utf8");
	const json = (p: string) => JSON.parse(readFileSync(join(root, p), "utf8"));
	return { files, surfaces: json("hub/ui-surfaces.json"), areas: json("hub/web-areas.json") };
}

const nodeId = (prefix: string, s: string) => `${prefix}_${s.replace(/[^\w]/g, "_")}`;
const label = (s: string) => s.replace(/"/g, "#quot;");
const byText = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

export function renderMap({ files, surfaces, areas }: MapInput): string {
	const areaOf = (file: string) => {
		if (file === "custom.js") return CUSTOM_AREA;
		const a = areas[file];
		if (typeof a !== "string") throw new Error(`hub/web-areas.json has no area for web/js/${file}`);
		return a;
	};
	const sites = extractOpenSitesFromText(files);
	const fileOfKey = new Map(sites.map(s => [s.key, s.file]));
	// Screens: the ui-surfaces.json entries with a view site; the area is that site's file's.
	const screens = new Map<string, { name: string; area: string }>();
	for (const e of surfaces) for (const k of e.sites) {
		const m = /^view:(.+)$/.exec(k), file = m && fileOfKey.get(k);
		if (m && file) screens.set(m[1]!, { name: e.name, area: areaOf(file) });
	}
	const overlays = new Map<string, number>(), edges = new Map<string, number>(), targets = new Set<string>();
	const bump = (m: Map<string, number>, k: string) => m.set(k, (m.get(k) ?? 0) + 1);
	for (const s of sites) {
		if (DECLARED.has(s.kind)) continue;
		const area = areaOf(s.file);
		if (s.kind !== "go") { bump(overlays, `${area}\t${s.kind}`); continue; }
		const target = /^go:[^:]+:([^:#]+)/.exec(s.key)?.[1] ?? "*";
		targets.add(target);
		bump(edges, `${area}\tgo\t${target}`);
	}
	const areaNames = [...new Set([...[...screens.values()].map(s => s.area), ...[...overlays.keys(), ...edges.keys()].map(k => k.split("\t")[0]!)])].sort(byText);
	const out = [
		"<!-- generated by hub/screen-map.ts; do not edit -->",
		"# Screen map",
		"",
		"Which screens each web area opens, and which overlays it shows. Generated from `web/js/*.js`, `web/custom.js`, `web/index.html`, `hub/ui-surfaces.json` and `hub/web-areas.json` by `bun hub/screen-map.ts`; `bun hub/screen-map.ts --check` fails when this file is stale.",
		"",
		"- a box is an area of `web/` (`custom` is `web/custom.js`); the rounded node inside is the area's own code",
		"- a screen sits in the area that declares its view; an arrow labelled `go (n)` is n `go()` calls from that area's code to the screen",
		"- `kind (n)` nodes are the overlays the area opens (dialog, ask, menu, toast, ...) with their number of call sites",
		"",
		"```mermaid",
		"flowchart LR",
	];
	for (const area of areaNames) {
		out.push(`  subgraph ${nodeId("a", area)}["${label(area)}"]`, `    ${nodeId("c", area)}(["${label(area)} code"])`);
		for (const [id, s] of [...screens].filter(([, s]) => s.area === area).sort(([a], [b]) => byText(a, b))) out.push(`    ${nodeId("s", id)}["${label(`${id}: ${s.name}`)}"]`);
		for (const [k, n] of [...overlays].filter(([k]) => k.startsWith(`${area}\t`)).sort(([a], [b]) => byText(a, b))) {
			const kind = k.split("\t")[1]!;
			out.push(`    ${nodeId(`o_${area}`, kind)}["${label(`${kind} (${n})`)}"]`);
		}
		out.push("  end");
	}
	// go() targets that are no declared screen: a computed name, or a literal with no view.
	for (const t of [...targets].filter(t => !screens.has(t)).sort(byText)) out.push(`  ${nodeId("s", t === "*" ? "any" : t)}["${label(t === "*" ? "(computed screen)" : `${t}: (no view)`)}"]`);
	for (const [k, n] of [...edges].sort(([a], [b]) => byText(a, b))) {
		const [area, kind, target] = k.split("\t") as [string, string, string];
		out.push(`  ${nodeId("c", area)} -->|"${kind} (${n})"| ${nodeId("s", target === "*" ? "any" : target)}`);
	}
	out.push("```", "");
	return out.join("\n");
}

// Lines that differ by position: "-" is in the file, "+" is what the code gives.
export function diffLines(file: string, want: string): string[] {
	const a = file.split("\n"), b = want.split("\n"), out: string[] = [];
	for (let i = 0; i < Math.max(a.length, b.length); i++) {
		if (a[i] === b[i]) continue;
		if (a[i] !== undefined) out.push(`${i + 1}: - ${a[i]}`);
		if (b[i] !== undefined) out.push(`${i + 1}: + ${b[i]}`);
	}
	return out;
}

if (import.meta.main) {
	const want = renderMap(readInput()), path = join(ROOT, MAP_FILE);
	if (process.argv.includes("--check")) {
		let have = "";
		try { have = readFileSync(path, "utf8"); } catch { console.error(`${MAP_FILE} is missing; run bun hub/screen-map.ts`); process.exit(1); }
		const diff = diffLines(have, want);
		if (diff.length) { console.error(`${MAP_FILE} is stale; run bun hub/screen-map.ts\n${diff.join("\n")}`); process.exit(1); }
		console.log(`${MAP_FILE} is current`);
	} else {
		writeFileSync(`${path}.tmp`, want);
		renameSync(`${path}.tmp`, path);
		console.log(`wrote ${MAP_FILE}`);
	}
}
